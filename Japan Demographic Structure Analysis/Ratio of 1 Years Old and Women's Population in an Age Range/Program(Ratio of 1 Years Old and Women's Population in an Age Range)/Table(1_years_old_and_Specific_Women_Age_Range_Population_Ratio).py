# Creates a check_order
def Check_Year_Order_keep_Value_from_latest_Source_Year(data):
    # Sort the "Year"
    def sort_year(year_str):
        year_str = str(year_str).strip()
        try:
            return int(year_str)
        except ValueError:
            return 999

    def sort_source_year(source_year_str):
        source_year_str = str(source_year_str).strip()
        try:
            return int(source_year_str)
        except ValueError:
            return 999

    data["Year_Sort"] = data["Year"].apply(sort_year)
    data["Source_Year_Sort"] = data["Source Year"].apply(sort_source_year)

    #Sort data by Year_Sort and Source_Year_Sort (descending for source year)
    data_fix = data.sort_values(by=["Year_Sort","Source_Year_Sort"],ascending=[True,False])

    #drop duplicate for the same Year and Area, keep the latest Source Year Data
    data_fix = data_fix.drop_duplicates(subset=["Year","Age"],keep="first")
    return data_fix

